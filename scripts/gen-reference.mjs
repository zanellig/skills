#!/usr/bin/env bun
// Regenerates skills/README.md and marked sections in existing category READMEs
// from each SKILL.md frontmatter.
// Usage: bun scripts/gen-reference.mjs [--check]
import { globSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative } from "node:path";

const OUT = "skills/README.md";
const GENERATED_START = "<!-- BEGIN GENERATED SKILL REFERENCE -->";
const GENERATED_END = "<!-- END GENERATED SKILL REFERENCE -->";

// Abbreviations whose period does not end a sentence. Only ones plausibly followed
// by a capitalised word are listed: a false entry costs a long summary, a missing
// one truncates mid-phrase. "etc." and "Inc." are deliberately absent — in a
// description they almost always sit at the end of the sentence.
const ABBREVIATIONS = [
  // English titles, Latin, measures
  "Dr", "Mr", "Mrs", "Ms", "Prof", "Sr", "Jr", "St", "Rev", "Gov", "Sen", "approx", "vs", "cf", "et", "al",
  // Spanish titles, references, common shorthand
  "Sra", "Srta", "Dra", "Dña", "art", "arts", "pág", "págs", "núm", "cap", "ed", "aprox", "ej",
  "EE", "UU", "Ud", "Uds", "Vd", "tel", "av", "Avda",
  // Month abbreviations
  "Jan", "Feb", "Mar", "Apr", "Jun", "Jul", "Aug", "Sep", "Sept", "Oct", "Nov", "Dec",
  "ene", "feb", "abr", "ago", "sept", "set", "oct", "nov", "dic",
];

// A trailing abbreviation: a lone letter (e.g., i.e., U.S., Ph.D., p. ej.) or a word
// from the list above. The leading non-letter keeps it from matching a word's last
// letter, so "semver tags." is a sentence end while "p." is not.
const ABBREV_END = new RegExp(`(?:^|[^\\p{L}])(?:\\p{L}|${ABBREVIATIONS.join("|")})\\.$`, "u");

// Sentence starts: a capital in any alphabet, or the Spanish opening ¿ / ¡.
const SENTENCE_START = /(?<=\.)\s+(?=[\p{Lu}¿¡])/u;

// First sentence of a description; the rest is trigger text ("Use when ...") that
// only the model needs.
export const summarize = (description) => {
  let summary = "";
  for (const sentence of description.trim().replace(/\s+/g, " ").split(SENTENCE_START)) {
    summary += (summary ? " " : "") + sentence;
    if (!ABBREV_END.test(summary)) break;
  }
  return summary;
};

const title = (s) => s.replace(/(^|[-\s])(\w)/g, (_, sep, c) => (sep === "-" ? " " : sep) + c.toUpperCase());

const loadSkills = () =>
  globSync("skills/**/SKILL.md")
    .sort()
    .map((path) => {
      const fm = readFileSync(path, "utf8").match(/^---\n([\s\S]*?)\n---/);
      if (!fm) throw new Error(`${path}: missing frontmatter`);
      const { name, description = "" } = Bun.YAML.parse(fm[1]);
      const parts = path.split("/"); // skills/[category/]name/SKILL.md
      return {
        name: name ?? parts.at(-2),
        category: parts.length > 3 ? parts[1] : "misc",
        summary: summarize(description),
        path,
        link: `./${parts.slice(1).join("/")}`,
      };
    });

export function render(skills = loadSkills()) {
  const body = [...new Set(skills.map((s) => s.category))]
    .sort()
    .map((cat) => {
      const lines = skills
        .filter((s) => s.category === cat)
        .map((s) => `- **[${s.name}](${s.link})** — ${s.summary}`)
        .join("\n");
      return `## ${title(cat)}\n\n${lines}`;
    })
    .join("\n\n");

  return { body: `<!-- Generated by scripts/gen-reference.mjs. Do not edit. -->\n\n# Reference\n\n${body}\n`, count: skills.length };
}

const renderCategory = (readme, current, skills) => {
  const directory = dirname(readme);
  const groups = new Map();
  for (const skill of skills.filter((skill) => skill.path.startsWith(`${directory}/`))) {
    const skillPath = relative(directory, skill.path);
    const group = skillPath.split("/").slice(0, -2).join("/");
    const lines = groups.get(group) ?? [];
    lines.push(`- **[${skill.name}](./${skillPath})** — ${skill.summary}`);
    groups.set(group, lines);
  }
  const reference = [...groups]
    .sort(([a], [b]) => (a === "" ? -1 : b === "" ? 1 : a.localeCompare(b)))
    .map(([group, lines]) => {
      const heading = group ? `## ${group.split("/").map(title).join(" / ")}\n\n` : "";
      return `${heading}${lines.join("\n")}`;
    })
    .join("\n\n");
  const generated = `${GENERATED_START}\n${reference}\n${GENERATED_END}`;
  const marked = new RegExp(`${GENERATED_START}[\\s\\S]*?${GENERATED_END}`);

  return marked.test(current)
    ? current.replace(marked, generated)
    : `${current.trimEnd()}\n\n${generated}\n`;
};

const readOrEmpty = (path) => {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return "";
  }
};

if (import.meta.main) {
  const skills = loadSkills();
  const { body, count } = render(skills);
  const targets = [
    { path: OUT, current: readOrEmpty(OUT), next: body },
    ...globSync("skills/**/README.md")
      .filter((path) => path !== OUT && !skills.some((skill) => dirname(skill.path) === dirname(path)))
      .sort()
      .map((path) => {
        const current = readFileSync(path, "utf8");
        return { path, current, next: renderCategory(path, current, skills) };
      }),
  ];
  const stale = targets.filter(({ current, next }) => current !== next);

  if (process.argv.includes("--check")) {
    for (const { path } of stale) console.error(`${path} is stale. Run: bun scripts/gen-reference.mjs`);
    if (stale.length) process.exit(1);
  } else {
    for (const { path, next } of stale) {
      writeFileSync(path, next);
      console.log(path === OUT ? `Updated ${path} (${count} skills).` : `Updated ${path}.`);
    }
  }
}
