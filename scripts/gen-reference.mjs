#!/usr/bin/env bun
// Regenerates skills/README.md from each SKILL.md frontmatter.
// Usage: bun scripts/gen-reference.mjs [--check]
import { globSync, readFileSync, writeFileSync } from "node:fs";

const OUT = "skills/README.md";

// First sentence of a description; the rest is trigger text ("Use when ...") that
// only the model needs. A period does not end a sentence when it belongs to an
// abbreviation: one with an internal period (e.g., i.e., U.S.), a short lowercase
// one (vs., cf.), or a title (Dr., Mr.). All-caps acronyms (PR., UI.) do end one,
// and so does "etc." — both are far more common at a sentence end than mid-sentence.
const SENTENCE_END = /(?<=(?<!\b\w\.\w)(?<!\b[a-z]{1,2})(?<!\b[A-Z][a-z])\.)\s+(?=[A-Z])/;
export const summarize = (description) => description.trim().replace(/\s+/g, " ").split(SENTENCE_END)[0];

const title = (s) => s.replace(/(^|[-\s])(\w)/g, (_, sep, c) => (sep === "-" ? " " : sep) + c.toUpperCase());

export function render() {
  const skills = globSync("skills/**/SKILL.md")
    .sort()
    .map((path) => {
      const fm = readFileSync(path, "utf8").match(/^---\n([\s\S]*?)\n---/);
      if (!fm) throw new Error(`${path}: missing frontmatter`);
      const { name, description = "" } = Bun.YAML.parse(fm[1]);
      const parts = path.split("/"); // skills/[category/]name/SKILL.md
      return {
        name: name ?? parts.at(-2),
        category: parts.length > 3 ? parts[1] : "misc",
        summary: summarize(description),
        link: `./${parts.slice(1).join("/")}`,
      };
    });

  const body = [...new Set(skills.map((s) => s.category))]
    .sort()
    .map((cat) => {
      const lines = skills
        .filter((s) => s.category === cat)
        .map((s) => `- **[${s.name}](${s.link})** — ${s.summary}`)
        .join("\n");
      return `## ${title(cat)}\n\n${lines}`;
    })
    .join("\n\n");

  return { body: `<!-- Generated by scripts/gen-reference.mjs. Do not edit. -->\n\n# Reference\n\n${body}\n`, count: skills.length };
}

if (import.meta.main) {
  const { body, count } = render();
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {}

  if (process.argv.includes("--check")) {
    if (body !== current) {
      console.error(`${OUT} is stale. Run: bun scripts/gen-reference.mjs`);
      process.exit(1);
    }
  } else if (body !== current) {
    writeFileSync(OUT, body);
    console.log(`Updated ${OUT} (${count} skills).`);
  }
}
